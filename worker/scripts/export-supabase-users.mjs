// One-time migration: export every Supabase auth user into a D1 seed file so
// existing accounts keep their user id (all D1 tables key on it) after the
// switch to our own Google OAuth.
//
// For each user it records:
//   id          — the Supabase auth UUID (unchanged, so folders/prompts/plans survive)
//   google_sub  — the Google account id from the user's google identity; the new
//                 auth flow looks users up by this on login. Users exported
//                 without one (shouldn't happen for Google-only auth) are
//                 claimed by verified email on their first login instead.
//
// Usage:
//   SUPABASE_SERVICE_ROLE_KEY=... node scripts/export-supabase-users.mjs
//   (optional: SUPABASE_URL=https://<project>.supabase.co to override)
//
// Then apply the generated file to the live DB:
//   wrangler d1 execute classorbit-db --remote --file=../supabase/seed-users.generated.sql
//
// The output contains user emails — don't commit it; delete it after applying.

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SUPABASE_URL = process.env.SUPABASE_URL || 'https://kuqwqukqsgkbnhkztpyw.supabase.co';
const SERVICE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!SERVICE_KEY) {
  console.error('Set SUPABASE_SERVICE_ROLE_KEY (Supabase dashboard → Project Settings → API keys).');
  process.exit(1);
}

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../../supabase/seed-users.generated.sql');
const PER_PAGE = 200;

function sql(value) {
  if (value === null || value === undefined || value === '') return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

// New-style secret keys (sb_secret_...) authenticate via the apikey header alone;
// legacy service_role JWTs must also go in the Authorization bearer.
const headers = SERVICE_KEY.startsWith('sb_secret_')
  ? { apikey: SERVICE_KEY }
  : { apikey: SERVICE_KEY, Authorization: `Bearer ${SERVICE_KEY}` };

async function fetchPage(page) {
  const res = await fetch(`${SUPABASE_URL}/auth/v1/admin/users?page=${page}&per_page=${PER_PAGE}`, {
    headers,
  });
  if (!res.ok) {
    throw new Error(`Supabase admin API ${res.status}: ${await res.text()}`);
  }
  const body = await res.json();
  return body.users ?? [];
}

const users = [];
for (let page = 1; ; page++) {
  const batch = await fetchPage(page);
  users.push(...batch);
  console.log(`page ${page}: ${batch.length} users`);
  if (batch.length < PER_PAGE) break;
}

// Newer GoTrue returns identities: null on the list endpoint; the per-user
// endpoint still includes them, and that's where the google sub lives.
for (const u of users) {
  if (u.identities) continue;
  const res = await fetch(`${SUPABASE_URL}/auth/v1/admin/users/${u.id}`, { headers });
  if (!res.ok) throw new Error(`Supabase admin API (user ${u.id}) ${res.status}: ${await res.text()}`);
  u.identities = (await res.json()).identities ?? [];
}

let missingSub = 0;
const lines = [
  '-- Generated by worker/scripts/export-supabase-users.mjs — do not commit (contains emails).',
  `-- Exported ${users.length} users from ${SUPABASE_URL} on ${new Date().toISOString()}.`,
];

for (const u of users) {
  const google = (u.identities ?? []).find((i) => i.provider === 'google');
  const googleSub = google?.identity_data?.sub ?? google?.id ?? null;
  if (!googleSub) missingSub++;
  const name = u.user_metadata?.full_name ?? u.user_metadata?.name ?? null;
  const avatar = u.user_metadata?.avatar_url ?? u.user_metadata?.picture ?? null;
  lines.push(
    'INSERT OR IGNORE INTO users (id, google_sub, email, name, avatar_url, created_at, last_login_at) ' +
      `VALUES (${sql(u.id)}, ${sql(googleSub)}, ${sql(u.email)}, ${sql(name)}, ${sql(avatar)}, ${sql(u.created_at)}, ${sql(u.last_sign_in_at)});`
  );
}

writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`\nWrote ${users.length} users to ${OUT}`);
if (missingSub) {
  console.warn(`${missingSub} user(s) had no google identity sub — they will be matched by verified email on first login.`);
}
console.log('\nApply with:\n  wrangler d1 execute classorbit-db --remote --file=../supabase/seed-users.generated.sql');
console.log('Delete the file afterwards — it contains user emails.');
